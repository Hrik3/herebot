#!/usr/bin/env python3
"""
E15 Historical Repair Pass (One-Time Offline Maintenance Operation)
===================================================================

Reconstructs historically corrupted word-state associations generated by the
old E15 cross-modal alignment bug using HereBot's native modules and strict
safety gates.

Invariants & Safety Gates:
1. Reconstructs from grounded evidence (conflict_history user-confirmations).
2. Never invents certainty or arbitrarily resolves symmetric 0.5/0.5 splits.
3. Clears ungrounded E15 spurious priors, leaving words clean for future
   CandidateLedger evidence accumulation.
4. Preserves conflict_history, conflict_cooldown, and pre-existing clean associations.
5. Generates an auditable record in curiosity_state/e15_repair_audit.json.
6. Strictly idempotent (e15_repair_version = 1).
"""

import json
import os
import sys
import time
from collections import Counter, defaultdict

# Ensure herebot is in pythonpath
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from components.directory_handler import STATE_DIR
from components.episodic_mem import EpisodicMemory
from components.factor_handler import StateManager
from components.learner import WordStateAssociator

REPAIR_VERSION = 1


def run_e15_historical_repair(state_dir: str = STATE_DIR, dry_run: bool = False) -> dict:
    word_state_path = os.path.join(state_dir, "word_state.json")
    audit_path = os.path.join(state_dir, "e15_repair_audit.json")

    # Check for existing repair pass (Idempotency check)
    if os.path.exists(audit_path):
        try:
            with open(audit_path, "r") as f:
                existing_audit = json.load(f)
            if existing_audit.get("e15_repair_version") == REPAIR_VERSION and not dry_run:
                print(f"[E15 Repair] State at '{state_dir}' was already repaired under version {REPAIR_VERSION}. Skipping (idempotent).")
                return existing_audit
        except Exception as e:
            print(f"[E15 Repair] Notice: could not read existing audit: {e}")

    # Load current word state
    orig_wsa = WordStateAssociator()
    orig_wsa.load(word_state_path)

    # Reconstruct legitimately confirmed associations
    user_confirmed = {}
    for ch in orig_wsa.conflict_history:
        if ch.get("kept"):
            user_confirmed[ch["word"]] = (ch["kept"], ch.get("interaction_index", 0))

    # Fresh WordStateAssociator to hold reconstructed state
    repaired_wsa = WordStateAssociator()

    audit_log = {
        "repair_pass_id": f"e15_repair_{int(time.time())}",
        "e15_repair_version": REPAIR_VERSION,
        "timestamp": time.time(),
        "dry_run": dry_run,
        "summary": {},
        "entries": [],
    }

    decisions_count = Counter()

    for word, old_labs in sorted(orig_wsa.word_to_labels.items()):
        old_dist = dict(old_labs)

        # Case 1: User confirmed via conflict_history
        if word in user_confirmed:
            kept_label, idx = user_confirmed[word]
            repaired_wsa.add_association(
                word,
                kept_label,
                confidence=1.0,
                source="e15_repair_user_confirmed",
                interaction_index=idx,
            )
            dec = "REPAIRED_USER_CONFIRMED"
            decisions_count[dec] += 1
            new_dist = dict(repaired_wsa.word_to_labels.get(word, {}))
            audit_log["entries"].append({
                "token": word,
                "old_state": old_dist,
                "decision": dec,
                "new_state": new_dist,
                "reason": f'User explicitly confirmed "{kept_label}" in interaction {idx}',
                "safety_gate_passed": "USER_CONFIRMED_EXCEPTION",
            })

        # Case 2: Clean single-label association (not an E15 corrupted pair)
        elif old_labs and set(old_labs.keys()) != {"greetings", "bright curiosity"}:
            for lab, conf in old_labs.items():
                repaired_wsa.add_association(
                    word,
                    lab,
                    confidence=float(conf),
                    source="e15_repair_preserved_clean",
                    interaction_index=0,
                )
            dec = "PRESERVED_CLEAN_ASSOCIATION"
            decisions_count[dec] += 1
            new_dist = dict(repaired_wsa.word_to_labels.get(word, {}))
            audit_log["entries"].append({
                "token": word,
                "old_state": old_dist,
                "decision": dec,
                "new_state": new_dist,
                "reason": "Word had specific non-E15 association",
                "safety_gate_passed": "CLEAN_PRESERVATION",
            })

        # Case 3: Empty words
        elif not old_labs:
            dec = "PRESERVED_UNLABELED"
            decisions_count[dec] += 1
            audit_log["entries"].append({
                "token": word,
                "old_state": old_dist,
                "decision": dec,
                "new_state": {},
                "reason": "Word was unlabeled in original state",
                "safety_gate_passed": "EMPTY_PRESERVATION",
            })

        # Case 4: E15 contaminated 0.5/0.5 pair (or drifted derivative)
        else:
            dec = "UNRESOLVED_SPURIOUS_E15_CLEARED"
            decisions_count[dec] += 1
            audit_log["entries"].append({
                "token": word,
                "old_state": old_dist,
                "decision": dec,
                "new_state": {},
                "reason": "Corrupted by E15 blanket cross-modal alignment without discriminating grounded evidence; cleared to allow clean future learning",
                "safety_gate_passed": "SAFETY_GATE_5_UNRESOLVED_SYMMETRIC_EVIDENCE",
            })

    # Preserve conflict history and cooldown
    repaired_wsa.conflict_history = list(orig_wsa.conflict_history)
    repaired_wsa.conflict_cooldown = dict(orig_wsa.conflict_cooldown)

    audit_log["summary"] = dict(decisions_count)

    if not dry_run:
        repaired_wsa.save(word_state_path)
        with open(audit_path, "w") as f:
            json.dump(audit_log, f, indent=2)
        print(f"[E15 Repair] Saved repaired state to '{word_state_path}'.")
        print(f"[E15 Repair] Saved audit trail to '{audit_path}'.")

    return audit_log


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description="E15 Historical Repair Pass")
    parser.add_argument("--dry-run", action="store_true", help="Perform dry run without modifying files")
    parser.add_argument("--state-dir", default=STATE_DIR, help="Directory containing word_state.json")
    args = parser.parse_args()

    result = run_e15_historical_repair(state_dir=args.state_dir, dry_run=args.dry_run)
    print("Repair Summary:")
    print(json.dumps(result["summary"], indent=2))
